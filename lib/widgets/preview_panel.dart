/// Image preview with zoom controls and fullscreen button.
class _ImagePreviewTile extends StatefulWidget {
  final FileItem item;
  final VoidCallback onFullScreen;

  const _ImagePreviewTile({
    required this.item,
    required this.onFullScreen,
  });

  @override
  State<_ImagePreviewTile> createState() => _ImagePreviewTileState();
}

class _ImagePreviewTileState extends State<_ImagePreviewTile> {
  double _scale = 1.0;

  void _zoomIn() => setState(() => _scale = (_scale + 0.5).clamp(1.0, 6.0));
  void _zoomOut() => setState(() => _scale = (_scale - 0.5).clamp(1.0, 6.0));

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    return SingleChildScrollView(
      child: Column(
        children: [
          // Entire image is tappable — opens fullscreen viewer
          Material(
            color: cs.surface,
            borderRadius: BorderRadius.circular(6),
            child: InkWell(
              onTap: widget.onFullScreen,
              borderRadius: BorderRadius.circular(6),
              child: ClipRRect(
                borderRadius: BorderRadius.circular(6),
                child: Transform.scale(
                  scale: _scale,
                  alignment: Alignment.topCenter,
                  child: ConstrainedBox(
                    constraints: const BoxConstraints(maxHeight: 320),
                    child: Image.file(
                      File(widget.item.path),
                      fit: BoxFit.contain,
                      cacheWidth: 1000,
                      errorBuilder: (_, _, _) => Icon(
                        Icons.broken_image,
                        size: 48,
                        color: cs.onSurfaceVariant,
                      ),
                    ),
                  ),
                ),
              ),
            ),
          ),
          const SizedBox(height: 8),
          // Zoom + fullscreen + open-with controls
          Row(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              _zoomBtn(Icons.remove, cs, _zoomOut),
              Padding(
                padding: const EdgeInsets.symmetric(horizontal: 8),
                child: Text(
                  '${(_scale * 100).round()}%',
                  style: TextStyle(color: cs.onSurfaceVariant, fontSize: 12),
                ),
              ),
              _zoomBtn(Icons.add, cs, _zoomIn),
              const SizedBox(width: 12),
              SizedBox(
                height: 32,
                child: FilledButton.tonalIcon(
                  onPressed: widget.onFullScreen,
                  icon: const Icon(Icons.fullscreen, size: 14),
                  label: const Text('Open', style: TextStyle(fontSize: 11)),
                  style: FilledButton.styleFrom(
                    padding: const EdgeInsets.symmetric(horizontal: 8),
                    minimumSize: Size.zero,
                    tapTargetSize: MaterialTapTargetSize.shrinkWrap,
                  ),
                ),
              ),
            ],
          ),
          const SizedBox(height: 8),
          FilledButton.tonalIcon(
            onPressed: () async {
              try {
                await OpenWithService.openDefault(widget.item.path);
              } catch (_) {
                if (context.mounted) {
                  ScaffoldMessenger.of(context).showSnackBar(
                    SnackBar(
                      content: const Text("We couldn't find an app that opens this file type"),
                      backgroundColor: OneDarkColors.red,
                    ),
                  );
                }
              }
            },
            icon: const Icon(Icons.open_in_new, size: 16),
            label: const Text('Open with…'),
          ),
        ],
      ),
    );
  }

  Widget _zoomBtn(IconData icon, ColorScheme cs, VoidCallback onTap) {
    return InkWell(
      onTap: onTap,
      borderRadius: BorderRadius.circular(4),
      child: Container(
        padding: const EdgeInsets.all(6),
        decoration: BoxDecoration(
          color: cs.surfaceContainerHighest,
          borderRadius: BorderRadius.circular(4),
        ),
        child: Icon(icon, size: 16, color: cs.onSurface),
      ),
    );
  }
}

/// Renders a video preview: a real frame thumbnail (extracted from the file
/// at ~1s in) overlaid with a big play button. Tapping opens the in-app
/// full-screen player. Falls back to a movie icon if the thumbnail cannot be
/// generated (corrupt file, unsupported codec, etc.).
class _VideoPreviewTile extends StatefulWidget {
  final String path;
  final String name;
  final VoidCallback onFullScreen;
  const _VideoPreviewTile({
    required this.path,
    required this.name,
    required this.onFullScreen,
  });

  @override
  State<_VideoPreviewTile> createState() => _VideoPreviewTileState();
}

class _VideoPreviewTileState extends State<_VideoPreviewTile> {
  String? _thumbPath;
  bool _thumbFailed = false;

  // Inline player state. Initialized lazily on first tap so we don't decode
  // a 1GB video the moment the user selects a file.
  VideoPlayerController? _controller;
  bool _controllerReady = false;
  String? _controllerError;
  bool _muted = true; // start muted to avoid surprise audio

  @override
  void initState() {
    super.initState();
    _generateThumb();
  }

  Future<void> _generateThumb() async {
    try {
      final tmp = await VideoThumbnail.thumbnailFile(
        video: widget.path,
        imageFormat: ImageFormat.JPEG,
        maxWidth: 480,
        quality: 70,
      );
      if (!mounted) return;
      setState(() => _thumbPath = tmp);
    } catch (_) {
      if (!mounted) return;
      setState(() => _thumbFailed = true);
    }
  }

  Future<void> _ensureController() async {
    if (_controller != null) return;
    final c = VideoPlayerController.file(
      File(widget.path),
      videoPlayerOptions: VideoPlayerOptions(mixWithOthers: true),
    );
    _controller = c;
    try {
      // initialize() can hang on Android 14+ for some codecs (HEVC, certain
      // MKV variants). Race it against a 6-second timeout so the user sees
      // a usable error instead of a permanent spinner, and fall back to the
      // full-screen player which uses the same controller but with more
      // surface area for diagnostics.
      await c.initialize().timeout(
            const Duration(seconds: 6),
            onTimeout: () => throw TimeoutException(
                'VideoPlayerController.initialize timed out'),
          );
      await c.setVolume(_muted ? 0 : 1);
      if (!mounted) return;
      setState(() {
        _controllerReady = true;
        _controllerError = null;
      });
    } catch (e) {
      // Discard the failed controller so a tap-to-retry works.
      try {
        c.dispose();
      } catch (_) {}
      _controller = null;
      if (!mounted) return;
      setState(() => _controllerError = e.toString());
    }
  }

  Future<void> _togglePlay() async {
    await _ensureController();
    if (!_controllerReady || !mounted) return;
    final c = _controller!;
    if (c.value.isPlaying) {
      await c.pause();
    } else {
      await c.play();
    }
    if (mounted) setState(() {});
  }

  Future<void> _toggleMute() async {
    if (_controller == null) return;
    final next = !_muted;
    await _controller!.setVolume(next ? 0 : 1);
    if (!mounted) return;
    setState(() => _muted = next);
  }

  String _format(Duration d) {
    final h = d.inHours;
    final m = d.inMinutes.remainder(60).toString().padLeft(2, '0');
    final s = d.inSeconds.remainder(60).toString().padLeft(2, '0');
    return h > 0 ? '$h:$m:$s' : '$m:$s';
  }

  @override
  void dispose() {
    _controller?.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    final cs = Theme.of(context).colorScheme;
    final c = _controller;

    // Inline player is ready — render the live player with controls.
    if (_controllerReady && c != null) {
      return Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          ClipRRect(
            borderRadius: BorderRadius.circular(4),
            child: AspectRatio(
              aspectRatio: c.value.aspectRatio == 0
                  ? 16 / 9
                  : c.value.aspectRatio,
              child: Container(
                color: Colors.black,
                child: Stack(
                  alignment: Alignment.bottomCenter,
                  children: [
                    Positioned.fill(
                      child: VideoPlayer(c),
                    ),
                    if (!c.value.isPlaying)
                      const Center(
                        child: Icon(
                          Icons.play_circle_filled,
                          size: 56,
                          color: Colors.white70,
                        ),
                      ),
                    Positioned(
                      left: 0,
                      right: 0,
                      bottom: 0,
                      child: Container(
                        decoration: const BoxDecoration(
                          gradient: LinearGradient(
                            begin: Alignment.topCenter,
                            end: Alignment.bottomCenter,
                            colors: [
                              Colors.transparent,
                              Colors.black54,
                            ],
                          ),
                        ),
                        padding: const EdgeInsets.fromLTRB(8, 12, 8, 6),
                        child: Row(
                          children: [
                            IconButton(
                              icon: Icon(
                                c.value.isPlaying
                                    ? Icons.pause
                                    : Icons.play_arrow,
                                color: Colors.white,
                              ),
                              onPressed: _togglePlay,
                              tooltip: c.value.isPlaying
                                  ? 'Pause'
                                  : 'Play',
                            ),
                            Expanded(
                              child: VideoProgressIndicator(
                                c,
                                allowScrubbing: true,
                                colors: VideoProgressColors(
                                  playedColor: cs.primary,
                                  bufferedColor: cs.onSurfaceVariant,
                                  backgroundColor: cs.outlineVariant,
                                ),
                              ),
                            ),
                            Text(
                              '${_format(c.value.position)} / ${_format(c.value.duration)}',
                              style: const TextStyle(
                                color: Colors.white,
                                fontSize: 10,
                              ),
                            ),
                            IconButton(
                              icon: Icon(
                                _muted ? Icons.volume_off : Icons.volume_up,
                                color: Colors.white,
                                size: 20,
                              ),
                              onPressed: _toggleMute,
                              tooltip: _muted ? 'Unmute' : 'Mute',
                            ),
                            IconButton(
                              icon: const Icon(
                                Icons.fullscreen,
                                color: Colors.white,
                                size: 20,
                              ),
                              onPressed: widget.onFullScreen,
                              tooltip: 'Open full screen',
                            ),
                          ],
                        ),
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ),
          const SizedBox(height: 4),
          Text(
            widget.name,
            style: TextStyle(color: cs.onSurface, fontSize: 12),
            overflow: TextOverflow.ellipsis,
          ),
        ],
      );
    }

    // Controller is initializing (after a tap) — show progress.
    if (_controller != null && !_controllerReady && _controllerError == null) {
      return AspectRatio(
        aspectRatio: 16 / 9,
        child: Container(
          decoration: BoxDecoration(
            color: cs.surface,
            borderRadius: BorderRadius.circular(4),
          ),
          child: Center(
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                CircularProgressIndicator(color: cs.primary),
                const SizedBox(height: 8),
                Text(
                  'Loading video…',
                  style: TextStyle(color: cs.onSurfaceVariant, fontSize: 12),
                ),
              ],
            ),
          ),
        ),
      );
    }

    // Controller errored.
    if (_controllerError != null) {
      return AspectRatio(
        aspectRatio: 16 / 9,
        child: Container(
          decoration: BoxDecoration(
            color: cs.surface,
            borderRadius: BorderRadius.circular(4),
          ),
          child: Center(
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                Icon(Icons.error_outline, color: cs.error, size: 36),
                const SizedBox(height: 4),
                Text(
                  'Cannot play video',
                  style: TextStyle(color: cs.onSurface, fontSize: 12),
                ),
                const SizedBox(height: 4),
                Text(
                  'Tap to open in full screen',
                  style: TextStyle(color: cs.primary, fontSize: 11),
                ),
              ],
            ),
          ),
        ),
      );
    }

    // Initial state — show thumbnail + a play button. Tapping the play
    // button initializes the inline player.
    return GestureDetector(
      onTap: _togglePlay,
      child: Column(
        children: [
          ClipRRect(
            borderRadius: BorderRadius.circular(4),
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxHeight: 320),
              child: AspectRatio(
                aspectRatio: 16 / 9,
                child: Container(
                  width: double.infinity,
                  color: cs.surface,
                  child: Stack(
                    fit: StackFit.expand,
                    children: [
                      if (_thumbPath != null)
                        Image.file(
                          File(_thumbPath!),
                          fit: BoxFit.cover,
                          errorBuilder: (_, _, _) => Center(
                            child: Icon(Icons.movie,
                                size: 64, color: cs.primary),
                          ),
                        )
                      else if (_thumbFailed)
                        Center(
                          child: Icon(Icons.movie,
                              size: 64, color: cs.primary),
                        )
                      else
                        Center(
                          child: CircularProgressIndicator(
                              color: cs.primary),
                        ),
                      Center(
                        child: Container(
                          decoration: const BoxDecoration(
                            color: Colors.black54,
                            shape: BoxShape.circle,
                          ),
                          padding: const EdgeInsets.all(12),
                          child: const Icon(
                            Icons.play_arrow,
                            color: Colors.white,
                            size: 40,
                          ),
                        ),
                      ),
                    ],
                  ),
                ),
              ),
            ),
          ),
          const SizedBox(height: 4),
          Text(
            widget.name,
            style: TextStyle(color: cs.onSurface, fontSize: 12),
            overflow: TextOverflow.ellipsis,
          ),
          Text(
            'Tap to play in preview',
            style: TextStyle(color: cs.onSurfaceVariant, fontSize: 11),
          ),
        ],
      ),
    );
  }
}
